
-- 복약 알림 시간 저장
CREATE TABLE IF NOT EXISTS public.med_reminder (
    reminder_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    history_id BIGINT NOT NULL
        REFERENCES public.med_use_history(history_id)
        ON DELETE CASCADE,

    remind_time TIME NOT NULL,

    timezone VARCHAR(64) NOT NULL DEFAULT 'Asia/Seoul',

    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uq_med_reminder_history_time
        UNIQUE (history_id, remind_time)
);

-- 활성화된 알림 시간 검색용
CREATE INDEX IF NOT EXISTS idx_med_reminder_due
ON public.med_reminder(remind_time)
WHERE is_enabled = TRUE;
