CREATE TABLE IF NOT EXISTS public.med_use_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL
        REFERENCES public.app_user(user_id) ON DELETE CASCADE,

    item_seq VARCHAR(20) NOT NULL,
    item_name VARCHAR(200) NOT NULL,

    start_date DATE NOT NULL,
    times_per_day SMALLINT,
    stopped_at DATE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_med_use_times
        CHECK (times_per_day BETWEEN 1 AND 24),

    CONSTRAINT ck_med_use_dates
        CHECK (stopped_at IS NULL OR stopped_at >= start_date)
);

CREATE INDEX IF NOT EXISTS idx_med_use_history_user
ON public.med_use_history(user_id);