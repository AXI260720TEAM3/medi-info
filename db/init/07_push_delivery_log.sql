CREATE TABLE IF NOT EXISTS public.push_delivery_log (
    delivery_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    reminder_id BIGINT NOT NULL
        REFERENCES public.med_reminder(reminder_id)
        ON DELETE CASCADE,

    subscription_id BIGINT NOT NULL
        REFERENCES public.push_subscription(subscription_id)
        ON DELETE CASCADE,

    scheduled_date DATE NOT NULL,

    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'sending', 'sent', 'failed')),

    attempt_count INTEGER NOT NULL DEFAULT 0,

    sent_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    UNIQUE (reminder_id, subscription_id, scheduled_date)
);